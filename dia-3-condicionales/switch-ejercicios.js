// EJERCICIO 2  Crear un menú de opciones con switch.

const opcion = 3;

switch (opcion) {
  case 1:
    console.log("sumar");
    break;
  case 2:
    console.log("restar");
    break;
  case 3:
    console.log("multiplicar");
    console.log("Has elegido multiplicar");

    break;
  case 4:
    console.log("dividir");
    break;
  default:
    console.log("opcion no valida");
    break;
}
