console.log(5 == "5");
console.log(5 === "5");
console.log(10 != "10");
console.log(10 !== "10");
console.log(0 == false);
console.log(0 === false);

// Diferencia entre == y ===:
// == hace una comparación débil: convierte los tipos automáticamente antes de comparar.
// === hace una comparación estricta: NO convierte tipos, compara valor Y tipo.
// Regla de oro: usar SIEMPRE === y !== para evitar errores inesperados.
